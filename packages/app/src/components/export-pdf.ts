// PDF export for calendar month
// Uses jsPDF to generate a downloadable PDF

import {
  EarthData, GregorianDateTime, ResultCalendar, FastType,
  getTithiName, getNaksatraName, getYogaName,
  matchFestivals,
} from '@gaurabda/core';

export async function exportMonthToPDF(
  earth: EarthData,
  year: number,
  month: number,
): Promise<void> {
  const { jsPDF } = await import('jspdf');

  const cal = new ResultCalendar();
  const startDate = GregorianDateTime.fromComponents(year, month, 1);
  startDate.TimezoneHours = earth.offsetUtcHours;
  cal.calculateMonth(earth, year, month);

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();

  // Title
  const monthName = GregorianDateTime.getMonthName(month);
  doc.setFontSize(18);
  doc.text(`Gaurabda Calendar - ${monthName} ${year}`, pageW / 2, 15, { align: 'center' });

  // Table setup
  const cols = ['Day', 'Tithi', 'Naksatra', 'Yoga', 'Sunrise', 'Sunset', 'Festivals'];
  const colW = [15, 28, 30, 28, 18, 18, pageW - 15 - 28 - 30 - 28 - 18 - 18 - 25];
  const startX = 10;
  let y = 25;

  // Header
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  let x = startX;
  for (let c = 0; c < cols.length; c++) {
    doc.text(cols[c], x + 1, y);
    x += colW[c];
  }
  y += 5;
  doc.setDrawColor(150);
  doc.line(startX, y - 2, pageW - 10, y - 2);

  // Rows
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);

  for (let i = 0; i < cal.pureCount; i++) {
    const day = cal.days[cal.BEFORE_DAYS + i];
    if (!day?.date) continue;

    const a = day.astrodata;
    const sr = a.sunRise;

    const festivals = matchFestivals(sr.tithi, a.masa, sr.paksa, day.sankranti_zodiac);
    const festText = festivals.map(f => f.name).join('; ');

    const isFasting = day.nFastID === FastType.FAST_EKADASI;

    if (isFasting) {
      doc.setFillColor(255, 255, 220);
      doc.rect(startX, y - 3, pageW - 20, 5, 'F');
    }

    x = startX;
    const row = [
      `${day.date.day}`,
      getTithiName(sr.tithi),
      getNaksatraName(sr.naksatra),
      getYogaName(sr.yoga),
      sr.toLongTimeString(),
      a.sunSet.toLongTimeString(),
      festText,
    ];

    for (let c = 0; c < row.length; c++) {
      const text = c === cols.length - 1
        ? doc.splitTextToSize(row[c], colW[c] - 2)
        : row[c];
      doc.text(text, x + 1, y);
      x += colW[c];
    }

    y += isFasting ? 6 : 5;

    // New page if needed
    if (y > pageH - 15) {
      doc.addPage();
      y = 15;
    }
  }

  // Footer
  doc.setFontSize(6);
  doc.setTextColor(150);
  doc.text(`Generated by Gaurabda Calendar`, startX, pageH - 5);

  doc.save(`gaurabda-${year}-${month.toString().padStart(2, '0')}.pdf`);
}
